-- 1. Display all available parking slots
SELECT s.slot_id, s.slot_type, z.level, pl.name AS parking_lot
FROM Slots s
JOIN Zones z ON s.zone_id = z.zone_id
JOIN ParkingLots pl ON z.lot_id = pl.lot_id
WHERE s.status = 'available';


-- 2. Count available slots in each parking lot
SELECT pl.lot_id, pl.name,
       COUNT(s.slot_id) AS available_slots
FROM ParkingLots pl
JOIN Zones z ON pl.lot_id = z.lot_id
JOIN Slots s ON z.zone_id = s.zone_id
WHERE s.status = 'available'
GROUP BY pl.lot_id, pl.name;


-- 3. Display customer reservation details
SELECT r.res_id, u.name AS customer,
       v.plate_no, r.start_time, r.end_time, r.status
FROM Reservations r
JOIN Users u ON r.user_id = u.user_id
JOIN Vehicles v ON r.vehicle_id = v.vehicle_id
ORDER BY r.start_time DESC;


-- 4. Display vehicle parking history
SELECT v.plate_no, u.name AS customer,
       ps.entry_time, ps.exit_time, s.slot_id
FROM ParkingSessions ps
JOIN Vehicles v ON ps.vehicle_id = v.vehicle_id
JOIN Users u ON v.user_id = u.user_id
JOIN Slots s ON ps.slot_id = s.slot_id
ORDER BY ps.entry_time DESC;


-- 5. Find currently active parking sessions
SELECT ps.session_id, v.plate_no,
       ps.entry_time, s.slot_id
FROM ParkingSessions ps
JOIN Vehicles v ON ps.vehicle_id = v.vehicle_id
JOIN Slots s ON ps.slot_id = s.slot_id
WHERE ps.exit_time IS NULL;


-- 6. Calculate total parking revenue
SELECT SUM(amount) AS total_revenue
FROM Payments;


-- 7. Calculate revenue generated by each parking lot
SELECT pl.name AS parking_lot,
       SUM(p.amount) AS total_revenue
FROM Payments p
JOIN ParkingSessions ps ON p.session_id = ps.session_id
JOIN Slots s ON ps.slot_id = s.slot_id
JOIN Zones z ON s.zone_id = z.zone_id
JOIN ParkingLots pl ON z.lot_id = pl.lot_id
GROUP BY pl.lot_id, pl.name;


-- 8. Count vehicles registered by each customer
SELECT u.user_id, u.name,
       COUNT(v.vehicle_id) AS total_vehicles
FROM Users u
LEFT JOIN Vehicles v ON u.user_id = v.user_id
GROUP BY u.user_id, u.name;


-- 9. Display electric vehicle charging details
SELECT cs.charge_id, v.plate_no,
       cs.kwh_used, cs.cost, ps.entry_time
FROM ChargingSessions cs
JOIN ParkingSessions ps ON cs.session_id = ps.session_id
JOIN Vehicles v ON ps.vehicle_id = v.vehicle_id;


-- 10. Display parking violations and fines
SELECT vio.violation_id, v.plate_no,
       vio.type, vio.fine_amount
FROM Violations vio
JOIN ParkingSessions ps ON vio.session_id = ps.session_id
JOIN Vehicles v ON ps.vehicle_id = v.vehicle_id;


-- 11. Display the latest sensor reading for each slot
SELECT sl.slot_id, sl.reading, sl.logged_at
FROM SensorLogs sl
WHERE sl.logged_at = (
    SELECT MAX(sl2.logged_at)
    FROM SensorLogs sl2
    WHERE sl2.slot_id = sl.slot_id
);


-- 12. Display pricing rules for each parking lot
SELECT pl.name AS parking_lot,
       pr.slot_type, pr.base_rate,
       pr.peak_multiplier
FROM PricingRules pr
JOIN ParkingLots pl ON pr.lot_id = pl.lot_id
ORDER BY pl.name, pr.slot_type;
